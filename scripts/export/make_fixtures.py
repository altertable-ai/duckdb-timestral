"""Generate parity fixtures: reference forecasts from Mistral's PyTorch `TimestralForecaster`.

For every case and model size this writes `test/data/parity/<size>/<case>_input.csv`
(`series_id, t, value`; an empty value is NULL) and `<case>_expected.csv` (`series_id, step, q01..q99`),
plus `test/sql/parity_<size>.test`, which checks the extension's `timestral_forecast` against them.

Usage: uv run python make_fixtures.py [--sizes 5m,28m,123m,209m]
"""

import argparse
import csv
from pathlib import Path

import numpy as np
from timestral import TimestralForecaster

from export_onnx import REPO_ROOT, REVISIONS

SEED = 20261020
QUANTILE_COLUMNS = ["q01", "q05", "q10", "q15", "q20", "q25", "q30", "q35", "q40", "q45", "q50", "q55", "q60",
                    "q65", "q70", "q75", "q80", "q85", "q90", "q95", "q99"]
TOLERANCE = 1e-4


def seasonal(rng, n, period, level=100.0, amplitude=10.0, noise=1.0, trend=0.0):
    t = np.arange(n)
    return level + trend * t + amplitude * np.sin(2 * np.pi * t / period) + noise * rng.standard_normal(n)


def build_cases(rng) -> list[tuple[str, int, list[np.ndarray]]]:
    """(case name, horizon, series); NaN marks a NULL value."""
    def with_nans(x, idx):
        x = x.copy()
        x[idx] = np.nan
        return x

    interior = seasonal(rng, 800, 24)
    counts = rng.poisson(3 + 2 * np.sin(2 * np.pi * np.arange(700) / 7)).astype(np.float64)
    return [
        ("short_20", 24, [rng.standard_normal(20).cumsum() + 50]),
        ("one_patch", 32, [seasonal(rng, 32, 8)]),
        ("non_multiple", 96, [rng.standard_normal(1000).cumsum() + 200]),
        ("long_truncate", 64, [seasonal(rng, 40000, 96, trend=0.001)]),
        ("horizon_1", 1, [seasonal(rng, 500, 12)]),
        ("rollout_1500", 1500, [seasonal(rng, 5000, 24, amplitude=5) + 3 * np.sin(2 * np.pi * np.arange(5000) / 168)]),
        ("interior_nulls", 48, [with_nans(interior, rng.random(800) < 0.1)]),
        ("leading_nulls", 48, [with_nans(seasonal(rng, 1000, 24), slice(0, 300))]),
        ("trailing_nulls", 48, [with_nans(seasonal(rng, 600, 24), slice(590, 600))]),
        ("constant", 32, [np.full(200, 7.0)]),
        ("nonnegative_counts", 64, [counts]),
        ("large_magnitude", 32, [1e9 + 1e6 * rng.standard_normal(400).cumsum()]),
        ("negative", 32, [seasonal(rng, 400, 20, level=-500.0, amplitude=20.0)]),
        ("multi_series", 40, [seasonal(rng, n, p, level=lv) for n, p, lv in
                              [(50, 7, 10.0), (333, 24, 1000.0), (1024, 96, -3.0), (2000, 12, 0.5), (4096, 48, 42.0)]]),
    ]


def write_csv(path: Path, header: list[str], rows) -> None:
    with path.open("w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)


def fmt(v: float) -> str:
    return "" if np.isnan(v) else repr(float(v))


def parity_test(size: str, cases) -> str:
    env = "TIMESTRAL_MODEL_PATH" if size == "5m" else "TIMESTRAL_MODEL_DIR"
    path_expr = "${TIMESTRAL_MODEL_PATH}" if size == "5m" else "${TIMESTRAL_MODEL_DIR}/timestral-" + size + ".onnx"
    checks = " AND ".join(f"abs(f.{q} - e.{q}) <= {TOLERANCE} * s.scale" for q in QUANTILE_COLUMNS)
    blocks = []
    for name, horizon, _ in cases:
        d = f"test/data/parity/{size}"
        blocks.append(f"""query I
WITH f AS (
    SELECT series_id, unnest(timestral_forecast(t, value, {horizon}), recursive := true)
    FROM '{d}/{name}_input.csv' GROUP BY series_id),
e AS (SELECT * FROM '{d}/{name}_expected.csv'),
s AS (SELECT series_id, greatest(max(abs(q01)), max(abs(q99)), 1e-6) AS scale FROM e GROUP BY ALL)
SELECT count(*) = (SELECT count(*) FROM e) AND bool_and({checks} AND f.forecast = f.q50)
FROM (SELECT *, row_number() OVER (PARTITION BY series_id ORDER BY t) AS step FROM f) f
JOIN e USING (series_id, step)
JOIN s USING (series_id);
----
true
""")
    return f"""# name: test/sql/parity_{size}.test
# description: timestral_forecast matches Mistral's PyTorch TimestralForecaster ({size} model)
# group: [sql]

# GENERATED by scripts/export/make_fixtures.py; do not edit by hand.
# Tolerance: |extension - reference| <= {TOLERANCE} x the series' largest |q01|/|q99|. The ONNX graph alone differs
# from PyTorch by up to ~4e-5 of the output scale (float32 kernels; see export_onnx.py verification).

require timestral

require-env {env}

statement ok
SET timestral_model_path = '{path_expr}';

""" + "\n".join(blocks)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sizes", default="5m,28m,123m,209m")
    args = parser.parse_args()
    for size in [s.strip().lower() for s in args.sizes.split(",")]:
        cases = build_cases(np.random.default_rng(SEED))
        repo, revision = REVISIONS[size]
        forecaster = TimestralForecaster.from_pretrained(repo, revision=revision, device="cpu")
        out = REPO_ROOT / "test" / "data" / "parity" / size
        out.mkdir(parents=True, exist_ok=True)
        for name, horizon, series in cases:
            inputs, expected = [], []
            for sid, values in enumerate(series):
                context = values.astype(np.float32)
                inputs += [(sid, t, fmt(v)) for t, v in enumerate(context)]
                q = forecaster.forecast(context, prediction_length=horizon).quantiles[0, 0].numpy()
                expected += [(sid, step + 1, *[fmt(v) for v in q[step]]) for step in range(horizon)]
            write_csv(out / f"{name}_input.csv", ["series_id", "t", "value"], inputs)
            write_csv(out / f"{name}_expected.csv", ["series_id", "step", *QUANTILE_COLUMNS], expected)
            print(f"{size} {name}: {len(series)} series, horizon {horizon}")
        write_parity_test(size, cases)


def write_parity_test(size: str, cases) -> None:
    (REPO_ROOT / "test" / "sql" / f"parity_{size}.test").write_text(parity_test(size, cases))


if __name__ == "__main__":
    main()
